-- Usuwamy wyłącznie polityki trzech tabel czatu i zakładamy kompletne od nowa.
do $$
declare
  policy_row record;
begin
  for policy_row in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('chat_conversations', 'chat_members', 'chat_messages')
  loop
    execute format(
      'drop policy if exists %I on %I.%I',
      policy_row.policyname,
      policy_row.schemaname,
      policy_row.tablename
    );
  end loop;
end $$;

create policy "chat_conversations_select_allowed"
on public.chat_conversations
for select
to authenticated
using (public.can_access_chat(id));

create policy "chat_members_select_own"
on public.chat_members
for select
to authenticated
using (user_id = auth.uid());

create policy "chat_messages_select_allowed"
on public.chat_messages
for select
to authenticated
using (
  conversation_id is not null
  and public.can_access_chat(conversation_id)
);

create policy "chat_messages_insert_allowed"
on public.chat_messages
for insert
to authenticated
with check (
  sender_id = auth.uid()
  and conversation_id is not null
  and public.can_access_chat(conversation_id)
);

