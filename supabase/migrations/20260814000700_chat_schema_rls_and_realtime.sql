-- Gdy id wiadomości jest identity/serial, rola authenticated potrzebuje
-- dostępu do przypisanej sekwencji. Blok działa też, gdy istniejąca tabela ma UUID.
do $$
declare
  message_id_sequence text;
begin
  select pg_get_serial_sequence('public.chat_messages', 'id')
  into message_id_sequence;

  if message_id_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to authenticated',
      message_id_sequence
    );
  end if;
end $$;

