-- GKS Strzegowo: bezpieczny model czatu dla Supabase
-- Skrypt jest niedestrukcyjny dla istniejących wiadomości:
-- stare kolumny recipient_id i channel zostają, ale nowa aplikacja już ich nie używa.

create extension if not exists pgcrypto;

create table if not exists public.chat_conversations (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('direct', 'staff')),
  conversation_key text not null unique,
  title text not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.chat_members (
  conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

-- Jeśli chat_messages już istnieje, zostanie rozszerzone bez kasowania danych.
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid references public.chat_conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender_name text,
  content text not null,
  created_at timestamptz not null default now()
);

alter table public.chat_messages
  add column if not exists conversation_id uuid references public.chat_conversations(id) on delete cascade;

alter table public.chat_messages
  add column if not exists sender_name text;

create index if not exists chat_members_user_id_idx
  on public.chat_members(user_id);

create index if not exists chat_messages_conversation_created_at_idx
  on public.chat_messages(conversation_id, created_at);

